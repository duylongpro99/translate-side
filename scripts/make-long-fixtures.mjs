// Generates fixtures/long/*.html (plan M5-E4/E5, handoff to M6): a 100-screen article and a page with a large
// table, both synthetic filler (MIT, no third-party text), deterministic. Run: node scripts/make-long-fixtures.mjs
import fs from 'node:fs';
import path from 'node:path';

const out = path.join(process.cwd(), 'fixtures/long');
fs.mkdirSync(out, { recursive: true });

let seed = 20261011;
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32);
const pick = (a) => a[Math.floor(rnd() * a.length)];
const SUBJECT = ['The scheduler', 'A small team', 'The harbour authority', 'Each volunteer', 'The old library', 'A careful reader', 'The survey crew', 'Our network', 'The committee', 'A travelling baker'];
const VERB = ['keeps track of', 'slowly rebuilt', 'rarely mentions', 'carefully compares', 'quietly depends on', 'openly questions', 'often forgets', 'gradually replaced', 'always checks', 'finally explained'];
const OBJECT = ['the morning shipments', 'a long list of repairs', 'every borrowed ladder', 'the narrow bridge schedule', 'several unfinished maps', 'the winter budget', 'a stack of handwritten notes', 'the quiet corner of the market', 'two competing proposals', 'the lighthouse records'];
const TAIL = ['before the weather turns', 'because nobody else would', 'while the tea gets cold', 'in the order they arrived', 'as the report was being written', 'long after the meeting ended', 'without telling the neighbours', 'although the numbers disagreed', 'whenever the tide allowed it', 'to avoid another delay'];
const sentence = () => `${pick(SUBJECT)} ${pick(VERB)} ${pick(OBJECT)} ${pick(TAIL)}.`;
const paragraph = (n = 3 + Math.floor(rnd() * 3)) => Array.from({ length: n }, sentence).join(' ');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const page = (title, body) => `<!doctype html>\n<!-- Synthetic filler generated by scripts/make-long-fixtures.mjs; MIT, no third-party text. -->\n<html lang="en"><head><meta charset="utf-8"><title>${title}</title>\n<style>body{font:16px/1.6 Georgia,serif;max-width:46rem;margin:2rem auto;padding:0 1rem}p{margin:0 0 1.1rem}table{border-collapse:collapse;width:100%}td,th{border:1px solid #bbb;padding:.3rem .5rem;text-align:left;vertical-align:top}figure{margin:1.5rem 0}</style></head>\n<body><article>\n${body}\n</article></body></html>\n`;

// A 100-screen article: ~900 blocks (about 9 per 800 px screen at this width, with headings, lists, figures).
{
  const parts = ['<h1>A very long field report on the harbour town</h1>', `<p>${paragraph(4)}</p>`];
  const SVG = 'data:image/svg+xml,%3Csvg xmlns=%22http://www.w3.org/2000/svg%22 width=%22600%22 height=%22160%22%3E%3Crect width=%22600%22 height=%22160%22 fill=%22%23dde%22/%3E%3C/svg%3E';
  for (let ch = 1; ch <= 45; ch++) {
    parts.push(`<h2>Chapter ${ch}: ${esc(pick(OBJECT))}</h2>`);
    for (let i = 0; i < 6; i++) parts.push(`<p>${paragraph()}</p>`);
    parts.push(`<ul>${Array.from({ length: 3 }, () => `<li>${sentence()}</li>`).join('')}</ul>`);
    parts.push(`<blockquote><p>${sentence()} ${sentence()}</p></blockquote>`);
    parts.push(`<figure><img src="${SVG}" alt="Sketch ${ch}: ${esc(pick(OBJECT))} drawn by the survey crew"><figcaption>Figure ${ch}. ${esc(sentence())}</figcaption></figure>`);
    parts.push(`<pre><code>harbour --chapter ${ch} --report</code></pre>`);
    for (let i = 0; i < 4; i++) parts.push(`<p>${paragraph()}</p>`);
  }
  fs.writeFileSync(path.join(out, 'long-100-screens.html'), page('A very long field report', parts.join('\n')));
}

// A large table: 120 rows × 5 columns, a caption, a header row, a column of short statuses.
{
  const STATUS = ['Open', 'Closed', 'Waiting for parts', 'Needs review', 'Scheduled'];
  const rows = Array.from({ length: 120 }, (_, i) => `<tr><td>R-${1000 + i}</td><td>${esc(pick(SUBJECT))} ${esc(pick(VERB))} ${esc(pick(OBJECT))}.</td><td>${pick(STATUS)}</td><td>${esc(sentence())}</td><td>${(rnd() * 900 + 100).toFixed(2)}</td></tr>`);
  const body = [
    '<h1>Repair log of the harbour town</h1>',
    `<p>${paragraph(2)}</p>`,
    `<table><caption>Table 1. Repair requests received this winter, with status and notes.</caption><thead><tr><th>Ticket</th><th>Summary</th><th>Status</th><th>Notes</th><th>Cost (EUR)</th></tr></thead><tbody>\n${rows.join('\n')}\n</tbody></table>`,
    `<p>${paragraph(3)}</p>`,
  ].join('\n');
  fs.writeFileSync(path.join(out, 'large-table.html'), page('Repair log', body));
}
