// Builds the generated parts of spikes/s8/ext from the repository's own sources:
//   ext/engine.js     the real translate@2 prompt, wire format, segment parser and repair plan (entries/engine-entry.ts)
//   ext/fixtures.json the translatable blocks of three site fixtures, read by the real extractor (entries/extract-fixtures.ts)
// Run from the repository root: `node spikes/s8/build.mjs` (needs the root `pnpm install`; esbuild and jsdom are devDependencies).
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

const HERE = import.meta.dirname;
const ROOT = path.resolve(HERE, '../..');
const EXT = path.join(HERE, 'ext');
const TMP = path.join(HERE, '.tmp');

// The product's `@/…` imports (tsconfig paths) resolve to src/.
const srcAlias = {
  name: 'src-alias',
  setup(build) {
    build.onResolve({ filter: /^@\// }, async (args) => {
      const r = await build.resolve(`./${args.path.slice(2)}`, { kind: args.kind, resolveDir: path.join(ROOT, 'src') });
      if (r.errors.length > 0) return { errors: r.errors };
      return { path: r.path };
    });
  },
};

async function buildEngine() {
  await esbuild.build({
    entryPoints: [path.join(HERE, 'entries/engine-entry.ts')],
    outfile: path.join(EXT, 'engine.js'),
    bundle: true,
    format: 'iife',
    globalName: 'S8Engine',
    platform: 'browser',
    target: 'chrome138',
    plugins: [srcAlias],
    banner: { js: '// Generated by spikes/s8/build.mjs from src/engine (translate@2, wire, seg-parser, repair). Do not edit.' },
    logLevel: 'warning',
  });
}

async function buildFixtures() {
  fs.mkdirSync(TMP, { recursive: true });
  const outfile = path.join(TMP, 'extract.mjs');
  try {
    await esbuild.build({
      entryPoints: [path.join(HERE, 'entries/extract-fixtures.ts')],
      outfile,
      bundle: true,
      format: 'esm',
      platform: 'node',
      target: 'node22',
      packages: 'external',
      plugins: [srcAlias],
      // tests/fixtures/load.ts locates fixtures/ from its own directory.
      define: { 'import.meta.dirname': JSON.stringify(path.join(ROOT, 'tests/fixtures')) },
      logLevel: 'warning',
    });
    const { extractFixtures, SLUGS } = await import(pathToFileURL(outfile).href);
    const blocks = extractFixtures(path.join(ROOT, 'fixtures/sites'));
    fs.writeFileSync(path.join(EXT, 'fixtures.json'), `${JSON.stringify({ generatedBy: 'spikes/s8/build.mjs', slugs: SLUGS, blocks })}\n`);
    for (const slug of SLUGS) console.log(`${slug}: ${blocks[slug].length} blocks`);
  } finally {
    fs.rmSync(TMP, { recursive: true, force: true });
  }
}

await buildEngine();
await buildFixtures();
console.log('built spikes/s8/ext/engine.js and spikes/s8/ext/fixtures.json');
